-- Nur diese Funktion darf die globale Auswertung lesen.
create or replace function public.get_bingo_summary(admin_password text)
returns table(target text, word text, mentions bigint)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1 from public.bingo_admin_config
    where singleton = true
      and password_hash = crypt(admin_password, password_hash)
  ) then
    raise exception 'invalid admin password';
  end if;

  return query
  select
    lower(trim(e.target)) as target,
    min(trim(e.word)) as word,
    count(*)::bigint as mentions
  from public.bingo_entries e
  where trim(e.word) <> ''
  group by lower(trim(e.target)), lower(trim(e.word))
  order by lower(trim(e.target)), count(*) desc, lower(trim(e.word));
end;
$$;

revoke all on function public.get_bingo_summary(text) from public;
grant execute on function public.get_bingo_summary(text) to anon;
