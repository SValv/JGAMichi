create extension if not exists pgcrypto;

create table if not exists public.bingo_entries (
  id bigint generated by default as identity primary key,
  client_id uuid not null,
  player text not null check (player in ('florian','justin','sergey','michael','michael pufe','viktor','simon')),
  target text not null check (target in ('florian','justin','sergey','michael','michael pufe','viktor','simon')),
  slot integer not null check (slot between 0 and 4),
  word text not null default '' check (char_length(word) <= 80),
  checked boolean not null default false,
  updated_at timestamptz not null default now(),
  unique (client_id, player, target, slot),
  check (player <> target)
);

alter table public.bingo_entries enable row level security;
revoke all on public.bingo_entries from anon, authenticated;
revoke all on sequence public.bingo_entries_id_seq from anon, authenticated;

-- Die Spielseite kann ausschließlich über diese eng begrenzte Funktion
-- genau einen ihrer lokalen Slots einfügen oder aktualisieren.
create or replace function public.upsert_bingo_entry(
  p_client_id uuid,
  p_player text,
  p_target text,
  p_slot integer,
  p_word text,
  p_checked boolean
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_player not in ('florian','justin','sergey','michael','michael pufe','viktor','simon')
     or p_target not in ('florian','justin','sergey','michael','michael pufe','viktor','simon')
     or p_player = p_target
     or p_slot not between 0 and 4
     or char_length(coalesce(p_word,'')) > 80 then
    raise exception 'invalid bingo entry';
  end if;

  insert into public.bingo_entries(client_id,player,target,slot,word,checked,updated_at)
  values (p_client_id,p_player,p_target,p_slot,coalesce(p_word,''),coalesce(p_checked,false),now())
  on conflict (client_id,player,target,slot)
  do update set
    word = excluded.word,
    checked = excluded.checked,
    updated_at = now();
end;
$$;

revoke all on function public.upsert_bingo_entry(uuid,text,text,integer,text,boolean) from public;
grant execute on function public.upsert_bingo_entry(uuid,text,text,integer,text,boolean) to anon;

-- Passwort-Hash getrennt und nicht öffentlich lesbar speichern.
create table if not exists public.bingo_admin_config (
  singleton boolean primary key default true check (singleton),
  password_hash text not null
);
alter table public.bingo_admin_config enable row level security;
revoke all on public.bingo_admin_config from anon, authenticated;

